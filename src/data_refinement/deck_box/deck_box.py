"""The in-memory, multi-game deck store, keyed on nocab_uuid alone.

See plans/deck_box.md for the full design this implements, and
src/data_refinement/card_binder/card_binder.py for the sibling this was
deliberately modeled on. DeckBox mirrors CardBinder's CRUD-by-uuid and
load/save shape only — it has NO AliasLedger and NO identity-collision
handling of any kind, because decks don't have the problem CardBinder's
non-trivial half exists to solve: the same card recurs across many raw
sources and has to collapse to one identity, but every raw row a
DeckExtractionStage sees is already a distinct deck instance, never
merged with another.

A nocab_uuid, once minted for a deck, is never regenerated by anything
in this file — a save()/load() round-trip returns the exact same uuid
for the exact same deck, always (see load()'s docstring).
"""

import json
from dataclasses import replace
from pathlib import Path
from typing import ClassVar, Iterable
from uuid import UUID

from src.schema.card import GenericDeck
from src.schema.game_id import GameId


class DeckBox:
    """In-memory, multi-game deck store, keyed by nocab_uuid.

    Single-consumer-per-instance is not the right frame here — this is
    the shared, generic storage capability every deck_box extraction
    stage (and, eventually, training) reads from and writes into.
    Construction is always empty (__init__ takes no arguments); load()
    is the sole populated-construction entry point.
    """

    DEFAULT_OUTPUT_DIR: ClassVar[Path] = Path("data/final/decks")
    DEFAULT_OUTPUT_NAME: ClassVar[str] = "{game}.jsonl"

    def __init__(self) -> None:
        """Construct an empty deck box.

        Prefer load([]) over calling this directly when the intent is
        "start empty for an extraction run" — this constructor exists
        because load() is itself built on top of it.

        Inputs: none.
        Output: none (constructor).
        Side effects: none.
        Exceptions: none.
        """
        self._decks_by_uuid: dict[UUID, GenericDeck] = {}

    # region CRUD by UUID

    def create(self, deck: GenericDeck) -> GenericDeck:
        """Insert a brand-new deck.

        Callers (DeckExtractionStage implementations) are expected to
        have already determined that deck.nocab_uuid is genuinely new
        — this method exists to catch the mistake of calling it twice
        for the same uuid, not to perform that determination itself.
        Unlike CardBinder.create(), there is no duplicate-CONTENT
        question to consider here: every extracted deck is its own
        new uuid by construction.

        Inputs:
            deck: the deck to insert. deck.nocab_uuid MUST NOT already
                be stored.
        Output: deck, unchanged (returned for symmetry with
            update()/replace(), which do return a possibly-different
            object).
        Side effects: mutates this box's in-memory store.
        Exceptions: raises ValueError if deck.nocab_uuid is already
            stored — use update() or replace() instead.

        Example:
            >>> box = DeckBox()
            >>> box.create(some_deck)
        """
        if deck.nocab_uuid in self._decks_by_uuid:
            raise ValueError(f"create: {deck.nocab_uuid} is already stored")
        self._upsert_deck(deck)
        return deck

    def create_if_absent(self, deck: GenericDeck) -> GenericDeck:
        """Insert deck only if deck.nocab_uuid isn't already stored.

        The counterpart to create() for callers whose id scheme is
        deliberately content-derived (e.g. a hash of card_nocab_uuids
        — see metrics/hash_utils.py's deck_uuid_from_cards()) and
        therefore expect the same id to legitimately recur across many
        calls — create() raises on every recurrence; this treats a
        recurrence as a no-op instead of an error. On a recurrence,
        deck is NOT compared against the stored value for equality —
        the existing entry wins unconditionally, on the assumption
        that identical ids from a content-derived scheme imply
        identical content.

        Inputs:
            deck: the deck to insert if deck.nocab_uuid is new.
        Output: the deck now stored under deck.nocab_uuid — deck
            itself on a genuinely new id, or whatever was already
            stored on a recurrence.
        Side effects: mutates this box's in-memory store only when
            deck.nocab_uuid is new.
        Exceptions: none.

        Example:
            >>> box = DeckBox()
            >>> box.create_if_absent(some_deck)
            >>> box.create_if_absent(some_deck)  # no-op, same id
        """
        existing = self._decks_by_uuid.get(deck.nocab_uuid)
        if existing is not None:
            return existing
        self._upsert_deck(deck)
        return deck

    def update(
        self,
        nocab_uuid: UUID,
        card_nocab_uuids: list[UUID] | None = None,
        name: str | None = None,
    ) -> GenericDeck:
        """Selectively overwrite fields of an already-stored deck.

        Unlike CardBinder.update() (which shallow-merges into a
        raw_content dict), GenericDeck has no dict-shaped field to
        merge — so "update" here means "overwrite whichever of
        card_nocab_uuids/name are given (not None), leave the rest
        untouched," the closest equivalent for a dataclass with only
        scalar/list fields. This is the "leave other fields alone"
        counterpart to replace()'s full swap.

        Inputs:
            nocab_uuid: identity of the deck to update. MUST already
                be stored.
            card_nocab_uuids: new full list of card nocab_uuids
                (unordered, duplicates meaningful — see this module's
                docstring), or None (default) to leave unchanged. This
                REPLACES the existing list wholesale; it is not a
                merge/append.
            name: new name, or None (default) to leave unchanged.
        Output: the updated GenericDeck as now stored.
        Side effects: mutates this box's in-memory store.
        Exceptions: raises KeyError if nocab_uuid isn't stored.

        Example:
            >>> box = DeckBox()
            >>> box.create(some_deck)
            >>> box.update(some_deck.nocab_uuid, name="Renamed Deck")
        """
        if nocab_uuid not in self._decks_by_uuid:
            raise KeyError(f"update: {nocab_uuid} is not stored")
        existing = self._decks_by_uuid[nocab_uuid]

        updated = replace(
            existing,
            card_nocab_uuids=(
                card_nocab_uuids
                if card_nocab_uuids is not None
                else existing.card_nocab_uuids
            ),
            name=name if name is not None else existing.name,
        )
        self._upsert_deck(updated)
        return updated

    def replace(self, nocab_uuid: UUID, deck: GenericDeck) -> GenericDeck:
        """Fully overwrite an already-stored deck's content.

        Every field of deck becomes the stored value for nocab_uuid —
        conceptually a delete-then-add, except nocab_uuid itself never
        changes. This is the "delete then add" counterpart to
        update()'s selective overwrite.

        Inputs:
            nocab_uuid: identity of the deck to replace. MUST already
                be stored.
            deck: the new full deck content. deck.nocab_uuid MUST
                equal nocab_uuid — this method swaps content, it does
                not move a deck to a different uuid.
        Output: deck, unchanged (returned for symmetry with update()).
        Side effects: mutates this box's in-memory store.
        Exceptions: raises KeyError if nocab_uuid isn't stored (use
            create() for a genuinely new uuid). Raises ValueError if
            deck.nocab_uuid != nocab_uuid.

        Example:
            >>> box = DeckBox()
            >>> box.create(some_deck)
            >>> box.replace(some_deck.nocab_uuid, updated_deck)
        """
        if deck.nocab_uuid != nocab_uuid:
            raise ValueError(
                f"replace: deck.nocab_uuid ({deck.nocab_uuid}) != target uuid ({nocab_uuid})"
            )
        if nocab_uuid not in self._decks_by_uuid:
            raise KeyError(f"replace: {nocab_uuid} is not stored")
        self._upsert_deck(deck)
        return deck

    def delete(self, nocab_uuid: UUID) -> None:
        """Remove a deck entirely.

        Inputs:
            nocab_uuid: identity of the deck to remove. MUST already
                be stored.
        Output: none.
        Side effects: mutates this box's in-memory store.
        Exceptions: raises KeyError if nocab_uuid isn't stored.

        Example:
            >>> box = DeckBox()
            >>> box.create(some_deck)
            >>> box.delete(some_deck.nocab_uuid)
        """
        if nocab_uuid not in self._decks_by_uuid:
            raise KeyError(f"delete: {nocab_uuid} is not stored")
        del self._decks_by_uuid[nocab_uuid]

    def get_by_uuid(self, nocab_uuid: UUID) -> GenericDeck | None:
        """Look up a deck by this system's own identity.

        Inputs:
            nocab_uuid: identity to look up.
        Output: the matching GenericDeck, or None if no deck has this
            nocab_uuid.
        Side effects: none.
        Exceptions: none.

        Example:
            >>> box = DeckBox.load([Path("data/final/decks/mtg.jsonl")])
            >>> box.get_by_uuid(some_uuid)
        """
        return self._decks_by_uuid.get(nocab_uuid)

    def all_uuids(self, source_game: GameId | None = None) -> Iterable[UUID]:
        """Every nocab_uuid currently stored in this box.

        Inputs:
            source_game: if given, only uuids for decks in this game
                are returned. None (default) returns every uuid this
                box holds, across every game it has loaded.
        Output: every matching nocab_uuid, in no particular guaranteed
            order.
        Side effects: none.
        Exceptions: none.

        Example:
            >>> box = DeckBox.load([Path("data/final/decks/mtg.jsonl")])
            >>> list(box.all_uuids(GameId.MTG))
        """
        if source_game is None:
            return self._decks_by_uuid.keys()
        return [
            nocab_uuid
            for nocab_uuid, deck in self._decks_by_uuid.items()
            if deck.source_game == source_game
        ]

    def all_decks(self, source_game: GameId) -> Iterable[GenericDeck]:
        """Every deck currently stored in this box for one game.

        Inputs:
            source_game: which game's decks to enumerate.
        Output: every GenericDeck in source_game, in no particular
            guaranteed order.
        Side effects: none.
        Exceptions: none.

        Example:
            >>> box = DeckBox.load([Path("data/final/decks/mtg.jsonl")])
            >>> list(box.all_decks(GameId.MTG))
        """
        return [
            deck
            for deck in self._decks_by_uuid.values()
            if deck.source_game == source_game
        ]

    # endregion CRUD by UUID

    # region Persistence

    @staticmethod
    def load(paths: list[Path]) -> "DeckBox":
        """Load and merge one or more per-game JSONL files into one box.

        Every row's nocab_uuid, as written by whatever save() produced
        that row, is reinserted UNCHANGED — no remapping of any kind.
        If the same nocab_uuid legitimately appears in more than one
        loaded path, last-path-wins (a plain overwrite) — paths are
        processed in the given order.

        load([]) — an empty list — is the sanctioned way to start a
        fresh, empty box.

        Inputs:
            paths: zero or more paths to data/final/decks/<game>.jsonl-
                shaped files. Files for different games can be mixed
                in one call.
        Output: a populated DeckBox containing every deck from every
            given path (last-path-wins on a uuid appearing more than
            once).
        Side effects: reads each path in paths.
        Exceptions: raises if any path in paths doesn't exist or
            contains a line that doesn't deserialize to a valid
            GenericDeck.

        Example:
            >>> box = DeckBox.load([Path("data/final/decks/mtg.jsonl")])
            >>> empty_box = DeckBox.load([])
        """
        box = DeckBox()
        for path in paths:
            with open(path, "r", encoding="utf-8") as box_file:
                for line in box_file:
                    row = json.loads(line)
                    deck = GenericDeck(
                        nocab_uuid=UUID(row["nocab_uuid"]),
                        source_game=GameId(row["source_game"]),
                        name=row["name"],
                        card_nocab_uuids=[
                            UUID(uuid_str) for uuid_str in row["card_nocab_uuids"]
                        ],
                    )
                    box._upsert_deck(deck)
        return box

    @staticmethod
    def default_output_path(source_game: GameId) -> Path:
        """The conventional save() path for one game's deck box file.

        A recommended default, not an enforced requirement.

        Inputs:
            source_game: which game's conventional path to compute.
        Output: DEFAULT_OUTPUT_DIR / DEFAULT_OUTPUT_NAME, formatted
            with source_game (e.g. data/final/decks/mtg.jsonl).
        Side effects: none — purely a path computation.
        Exceptions: none.

        Example:
            >>> DeckBox.default_output_path(GameId.MTG)
            PosixPath('data/final/decks/mtg.jsonl')
        """
        return DeckBox.DEFAULT_OUTPUT_DIR / DeckBox.DEFAULT_OUTPUT_NAME.format(
            game=source_game.value
        )

    def save(self, path: Path, source_game: GameId) -> None:
        """Write this box's decks for one game to path, as JSONL.

        Only decks with deck.source_game == source_game are written.

        Inputs:
            path: destination file (e.g.
                data/final/decks/<game>.jsonl). Overwritten if it
                already exists.
            source_game: which game's subset of this box to write.
        Output: none.
        Side effects: creates path's parent directory if missing;
            writes/overwrites path.
        Exceptions: raises on failure to write path.

        Example:
            >>> box.save(Path("data/final/decks/mtg.jsonl"), GameId.MTG)
        """
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8") as box_file:
            for deck in self._decks_by_uuid.values():
                if deck.source_game != source_game:
                    continue
                row = {
                    "nocab_uuid": str(deck.nocab_uuid),
                    "source_game": deck.source_game.value,
                    "name": deck.name,
                    "card_nocab_uuids": [
                        str(nocab_uuid) for nocab_uuid in deck.card_nocab_uuids
                    ],
                }
                box_file.write(json.dumps(row) + "\n")

    # endregion Persistence

    # region Private Helpers

    def _upsert_deck(self, deck: GenericDeck) -> None:
        """Insert or overwrite deck in this box's store.

        Private helper — shared by create()/update()/replace()/load(),
        the only places that ever need to actually mutate storage.
        None of them enforce any invariant here (that's each public
        method's own job before calling this) — this method just
        stores whatever it's given.

        Inputs:
            deck: the deck to store as canonical for its nocab_uuid.
        Output: none.
        Side effects: mutates this box's store.
        Exceptions: none.
        """
        self._decks_by_uuid[deck.nocab_uuid] = deck

    # endregion Private Helpers
