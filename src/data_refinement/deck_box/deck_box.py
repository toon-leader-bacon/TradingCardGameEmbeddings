"""The multi-game deck store, backed by one SQLite file per game.

See plans/deckbox_sqlite.md for the full design this implements (the
architecture discussion that motivated it, and the corrections made
after two rounds of critic review), and
src/data_refinement/card_binder/card_binder.py for the sibling this was
originally modeled on. DeckBox mirrors CardBinder's CRUD-by-uuid shape
only - it has NO AliasLedger and NO identity-collision handling of any
kind, because decks don't have the problem CardBinder's non-trivial
half exists to solve (see this container's README).

THIS FILE WAS REWRITTEN from a pure in-memory dict
(dict[UUID, GenericDeck]) onto SQLite - the in-memory version could not
scale to seventeenlands_game_data's ~15-20M decks, and more importantly
could never scale to the eventual goal of one combined DeckBox holding
every MTG source, since load()/all_decks()/get_by_uuid() all assumed
full in-memory residency for every future operation, not just first
population.

THE LOAD/SAVE RELATIONSHIP, precisely (see load()/save()'s own
docstrings for the authoritative statement):
    - DeckBox() / load([]): a fresh ":memory:" connection, no path
      association.
    - load([one_path]): ALWAYS connects directly to one_path, whether
      or not it exists yet. From that point on, every mutating call
      (create/create_if_absent/update/replace/delete) wraps its own
      row write(s) - its own deck row, its deck_cards rows, and any
      metadata invalidation - in `with self._connection:`, which
      commits ONCE on a clean return and rolls back everything that
      call touched if it raises OR if the process is killed before
      that point - either way, the database ends up exactly as if the
      call had never been made, never a half-written row. There is no
      separate in-memory representation to flush. This is deliberate:
      an earlier design only direct-connected when one_path already
      existed, which meant a brand-new source's first-ever ingestion
      still accumulated entirely in memory and lost everything on a
      crash - exactly the failure this rewrite exists to fix.
    - load([2+ paths]): always a fresh ":memory:" merge. No given path
      is ever mutated - this is a genuine read, unlike the single-path
      case above.

CRASH-SAFETY OF THE VERSION STAMP: because a single-path box now
persists writes immediately, a run that crashes partway through
updating an EXISTING box must not leave metadata.card_binder_version
claiming a version that no longer accurately describes every row. Every
mutating call touching a given source_game clears (deletes) that game's
metadata row, inside the same `with self._connection:` block as the row
write(s) that follow it (unconditionally - deleting an already-absent
row is a cheap no-op, not something worth caching "already done" for;
see _invalidate_metadata_if_needed()'s own docstring for why a
Python-side cache was tried and removed). A pure-read session never
touches metadata. A crash - or a caught, retried exception - mid-write
therefore leaves metadata ABSENT for that game rather than falsely
matching a stale version - card_binder_version_for() returning None for
an absent
row is the existing, documented contract, and existing callers already
treat None as untrustworthy (see e.g.
src/dojos/contrastive/dojo.py's ContrastiveDojo._check_deck_box_version()).
save() re-establishes the row only once a run completes without error.

THIS MAKES IDEMPOTENT-RETRY A LOAD-BEARING ASSUMPTION, not just a nice
property: a crash-then-retry only converges to correct final content
because every current DeckExtractionStage derives a deterministic
identity and does get_by_uuid()-then-create()-or-update() (see
extraction.py's own docstring). A hypothetical future stage using
create() with a fresh, non-deterministic uuid per row would silently
duplicate content on any crash+retry under this direct-connect model -
previously harmless under the old load-everything/save-once model,
since it never left partial writes on disk for a retry to encounter.

A nocab_uuid, once minted for a deck, is never regenerated by anything
in this file - a save()/load() round-trip returns the exact same uuid
for the exact same deck, always.
"""

