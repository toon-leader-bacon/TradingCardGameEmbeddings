def list_known_refs() -> list[SeventeenLandsFileRef]:
    """Build every SeventeenLandsFileRef in _KNOWN_VALID_TRIPLES.

    Inputs: none.
    Output: one SeventeenLandsFileRef per entry in
        _KNOWN_VALID_TRIPLES, sorted by (data_type, expansion,
        format_code) for deterministic ordering — this list feeds
        SeventeenLandsDownloader.download()'s tqdm progress bar, where
        a stable order makes repeated runs easier to compare.
    Side effects: none — no network I/O, this is a static table.
    Exceptions: none.

    Example:
        >>> refs = list_known_refs()
        >>> len(refs)
        303
    """
    return [
        SeventeenLandsFileRef.from_known(data_type, expansion.value, fmt.value)
        for data_type, expansion, fmt in sorted(
            _KNOWN_VALID_TRIPLES,
            key=lambda triple: (triple[0].value, triple[1].value, triple[2].value),
        )
    ]
