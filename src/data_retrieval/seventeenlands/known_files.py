"""A static snapshot of every (data_type, expansion, format_code) triple
17Lands has actually published a file for, as of 2026-09-06.

Third way to produce SeventeenLandsFileRefs, alongside the two
described in refs.py's module docstring. Exists because validity here
isn't systematic — e.g. STX+Sealed only ever got a GAME file, never
DRAFT or REPLAY — so neither "try the full cartesian product of every
enum value" nor a runtime fetch can derive it:
https://www.17lands.com/public_datasets is a client-rendered SPA (its
table is populated by JS after load), so a plain GET returns an empty
shell with no links in it — LandingPageParser can't be pointed at the
live URL directly. This table was produced by saving that page's
fully-rendered HTML (from a real browser) to disk and running
LandingPageParser against the saved file once, by hand.

To refresh: open https://www.17lands.com/public_datasets in a browser,
save the fully-rendered page HTML, then re-run LandingPageParser().parse()
against it and regenerate _KNOWN_VALID_TRIPLES below. There's no way to
automate that refresh from within this codebase without a
JS-rendering dependency this project doesn't have.

_KNOWN_VALID_TRIPLES is typed with the Expansion/FormatCode enums
(not bare strings) deliberately: this table is transcribed by hand
from a scrape, so a typo'd literal (e.g. "PremierDarft") would
otherwise pass silently and only surface as a 404 at download time —
using the enums makes an unrecognized code a NameError/AttributeError
at import time instead. list_known_refs() converts to .value only at
the from_known() call site, since that factory's own signature takes
plain strings (see refs.py).
"""

